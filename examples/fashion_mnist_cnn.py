from dptiny.data.fashion_mnist import get_fashion_mnist, CLASSES

print("Fashion-MNIST loader imported successfully!")
print("Classes:", CLASSES)

import numpy as np

from dptiny import (
    Variable,
    is_available,
    is_gpu,
    no_grad,
    softmax_cross_entropy,
    test_mode,
    to_cpu,
    to_gpu,
    use_gpu,
    xp,
)
from dptiny.data import DataLoader
from dptiny.data.fashion_mnist import CLASSES, get_fashion_mnist
from dptiny.nn import (
    Conv2d,
    Dropout,
    Flatten,
    Linear,
    MaxPool2d,
    ReLU,
    Sequential,
)
from dptiny.optim import Adam


xp.random.seed(0)

if is_available():
    use_gpu()
    print("GPU enabled for training.")
else:
    print("Training on CPU.")

print("Loading Fashion-MNIST dataset...")

X_train, X_test, y_train, y_test = get_fashion_mnist(
    normalize=False,
    flatten=False,
)

mean = X_train.mean()
std = X_train.std()

if std == 0:
    raise ValueError("Training data standard deviation is zero.")

X_train = ((X_train - mean) / std).astype(np.float32)
X_test = ((X_test - mean) / std).astype(np.float32)

if is_gpu():
    X_train = to_gpu(X_train)
    X_test = to_gpu(X_test)
    y_train = to_gpu(y_train)
    y_test = to_gpu(y_test)

model = Sequential(
    Conv2d(1, 16, 3, pad=1),
    ReLU(),
    MaxPool2d(2),
    Conv2d(16, 32, 3, pad=1),
    ReLU(),
    MaxPool2d(2),
    Flatten(),
    Linear(32 * 7 * 7, 128),
    ReLU(),
    Dropout(0.3),
    Linear(128, 10),
)

if is_gpu():
    model.to_gpu()

batch_size = 64
max_epoch = 10

train_loader = DataLoader(
    (X_train, y_train), batch_size=batch_size
)
test_loader = DataLoader(
    (X_test, y_test), batch_size=batch_size, shuffle=False
)

optimizer = Adam(model, lr=0.001)

for epoch in range(max_epoch):
    total_loss = 0.0
    total_correct = 0
    total_samples = 0

    model.train()

    for x, t in train_loader:
        y = model(Variable(x))
        loss = softmax_cross_entropy(y, t)

        model.cleargrads()
        loss.backward()
        optimizer.update()

        n = len(t)
        total_loss += float(loss.data) * n
        total_correct += int(
            to_cpu((y.data.argmax(axis=1) == t).sum())
        )
        total_samples += n

    train_loss = total_loss / total_samples
    train_accuracy = total_correct / total_samples

    test_correct = 0
    test_samples = 0

    with test_mode(), no_grad():
        for x, t in test_loader:
            predictions = model(Variable(x)).data.argmax(axis=1)
            test_correct += int(
                to_cpu((predictions == t).sum())
            )
            test_samples += len(t)

    test_accuracy = test_correct / test_samples

    print(
        f"Epoch {epoch + 1}/{max_epoch} | "
        f"Loss: {train_loss:.4f} | "
        f"Train accuracy: {train_accuracy:.4f} | "
        f"Test accuracy: {test_accuracy:.4f}"
    )

confusion = np.zeros((10, 10), dtype=np.int64)

with test_mode(), no_grad():
    for x, t in test_loader:
        predictions = np.asarray(
            to_cpu(model(Variable(x)).data.argmax(axis=1)),
            dtype=np.int64,
        )
        labels = np.asarray(to_cpu(t), dtype=np.int64)
        np.add.at(confusion, (labels, predictions), 1)

print("\nConfusion matrix (rows: true, columns: predicted):")
print(confusion)

print("\nPer-class accuracy:")

for i, name in enumerate(CLASSES):
    count = confusion[i].sum()
    accuracy = confusion[i, i] / count if count else 0.0
    print(f"{name}: {accuracy:.4f}")

best_pair = (0, 1)
best_count = -1

for i in range(10):
    for j in range(i + 1, 10):
        mistakes = confusion[i, j] + confusion[j, i]

        if mistakes > best_count:
            best_pair = (i, j)
            best_count = mistakes

print(
    f"\nMost confused pair: {CLASSES[best_pair[0]]} and "
    f"{CLASSES[best_pair[1]]} ({best_count} mistakes)"
)

print("\nTraining and evaluation complete!")

