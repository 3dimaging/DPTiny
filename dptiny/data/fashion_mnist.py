def _parse_idx(raw):
    if len(raw) < 4:
        raise ValueError("IDX file is too short")

    if raw[:2] != b"\x00\x00" or raw[2] != 8:
        raise ValueError("Invalid IDX header or data type")

    dimensions = raw[3]

    if dimensions == 0:
        raise ValueError("IDX file has no dimensions")

    header_size = 4 + 4 * dimensions

    if len(raw) < header_size:
        raise ValueError("IDX header is incomplete")

    shape = tuple(
        int.from_bytes(
            raw[4 + 4 * i:8 + 4 * i], "big"
        )
        for i in range(dimensions)
    )

    expected_size = int(np.prod(shape, dtype=np.int64))

    if len(raw) - header_size != expected_size:
        raise ValueError("IDX data size does not match header")

    return np.frombuffer(
        raw, dtype=np.uint8, offset=header_size
    ).reshape(shape).copy()


def _download(filename, cache_dir):
    path = os.path.join(cache_dir, filename)

    if os.path.isfile(path):
        return path

    fd, temporary_path = tempfile.mkstemp(
        dir=cache_dir, suffix=".part"
    )

    try:
        with os.fdopen(fd, "wb") as output:
            request = urllib.request.Request(
                _BASE_URL + filename,
                headers={"User-Agent": "Python"},
            )

            with urllib.request.urlopen(
                request, timeout=60
            ) as response:
                while True:
                    chunk = response.read(1024 * 1024)

                    if not chunk:
                        break

                    output.write(chunk)

        os.replace(temporary_path, path)

    except BaseException:
        if os.path.exists(temporary_path):
            os.remove(temporary_path)
        raise

    return path


def _read_idx(path):
    try:
        with gzip.open(path, "rb") as file:
            raw = file.read()
    except (OSError, EOFError) as error:
        raise ValueError(
            f"Unable to read compressed IDX file: {path}"
        ) from error

    return _parse_idx(raw)


def get_fashion_mnist(
    normalize=True,
    flatten=True,
    data_home=None,
):
    cache_root = (
        data_home if data_home is not None else _CACHE_DIR
    )

    cache_dir = os.path.join(
        cache_root, "fashion-mnist"
    )
    os.makedirs(cache_dir, exist_ok=True)

    dataset = {}

    for key, filename in _FILES.items():
        filepath = _download(filename, cache_dir)
        dataset[key] = _read_idx(filepath)

    X_train = dataset["train_images"]
    X_test = dataset["test_images"]
    y_train = dataset["train_labels"]
    y_test = dataset["test_labels"]

    expected_shapes = (
        X_train.shape == (60000, 28, 28)
        and X_test.shape == (10000, 28, 28)
        and y_train.shape == (60000,)
        and y_test.shape == (10000,)
    )

    if not expected_shapes:
        raise ValueError("Unexpected Fashion-MNIST dimensions")

    X_train = X_train.astype(np.float32)
    X_test = X_test.astype(np.float32)

    if normalize:
        X_train /= 255.0
        X_test /= 255.0

    if flatten:
        X_train = X_train.reshape(60000, 784)
        X_test = X_test.reshape(10000, 784)
    else:
        X_train = X_train.reshape(60000, 1, 28, 28)
        X_test = X_test.reshape(10000, 1, 28, 28)

    return (
        X_train,
        X_test,
        y_train.astype(np.int32),
        y_test.astype(np.int32),
    )

